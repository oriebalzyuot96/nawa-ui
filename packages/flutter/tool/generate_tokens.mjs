#!/usr/bin/env node
// Generates lib/src/tokens.g.dart from the Orca UI core theme source
// (packages/core/src/themes.mjs) using the same resolver the web build uses
// (packages/core/scripts/resolve.mjs), so Flutter colors match the CSS exactly.
//
//   node packages/flutter/tool/generate_tokens.mjs           # write the file
//   node packages/flutter/tool/generate_tokens.mjs --check   # fail if the file is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  shapes,
  softMix,
  defaultMode,
  defaultAccent,
  defaultShape,
} from '../../core/src/themes.mjs';
import { accentNames, modeNames, resolveTheme } from '../../core/scripts/resolve.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'lib', 'src', 'tokens.g.dart');

// `default` is a reserved word in Dart, so that shape is exposed as `standard`.
const shapeName = (name) => (name === 'default' ? 'standard' : name);

const colorKeys = [
  'primary',
  'primaryHover',
  'primaryInk',
  'onPrimary',
  'primarySoft',
  'focus',
  'surface',
  'surfaceAlt',
  'surfaceMuted',
  'text',
  'textMuted',
  'border',
  'controlBorder',
  'success',
  'warning',
  'danger',
  'info',
  'onDanger',
  'successSoft',
  'warningSoft',
  'dangerSoft',
  'infoSoft',
  'overlay',
];

const hex2 = (n) => n.toString(16).padStart(2, '0').toUpperCase();

/** '#rrggbb' | '#rgb' | 'rgba(r, g, b, a)' -> 'Color(0xAARRGGBB)'. */
function dartColor(value) {
  const v = value.trim();
  if (v.startsWith('#')) {
    let h = v.slice(1);
    if (h.length === 3) h = h.split('').map((c) => c + c).join('');
    if (h.length !== 6) throw new Error(`Unsupported hex color: ${value}`);
    return `Color(0xFF${h.toUpperCase()})`;
  }
  const m = v.match(/^rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+)\s*)?\)$/);
  if (!m) throw new Error(`Unsupported color: ${value}`);
  const [r, g, b] = [m[1], m[2], m[3]].map((x) => Math.round(Number(x)));
  const a = m[4] === undefined ? 255 : Math.round(Number(m[4]) * 255);
  return `Color(0x${hex2(a)}${hex2(r)}${hex2(g)}${hex2(b)})`;
}

function generate() {
  const lines = [];
  const w = (s = '') => lines.push(s);
  w('// GENERATED by tool/generate_tokens.mjs from packages/core/src/themes.mjs.');
  w('// Do not edit by hand. Run: node packages/flutter/tool/generate_tokens.mjs');
  w();
  w("import 'dart:ui' show Brightness, Color;");
  w();
  w("import 'theme/colors.dart';");
  w();
  w('/// Color mode of a resolved theme. `hc` is the high-contrast (light) mode.');
  w(`enum OrcaMode { ${modeNames.join(', ')} }`);
  w();
  w('/// Accent palette.');
  w(`enum OrcaAccent { ${accentNames.join(', ')} }`);
  w();
  w('/// Corner radius preset. `standard` is the web `default` shape.');
  w(`enum OrcaShape { ${Object.keys(shapes).map(shapeName).join(', ')} }`);
  w();
  w('/// Default mode, accent and shape (same as the web defaults).');
  w(`const OrcaMode orcaDefaultMode = OrcaMode.${defaultMode};`);
  w(`const OrcaAccent orcaDefaultAccent = OrcaAccent.${defaultAccent};`);
  w(`const OrcaShape orcaDefaultShape = OrcaShape.${shapeName(defaultShape)};`);
  w();
  w('/// Amount of the accent mixed into the surface for `primarySoft`.');
  w(`const double orcaSoftMixPrimary = ${softMix.primary};`);
  w();
  w('/// Amount of a status color mixed into the surface for `*Soft` tints.');
  w(`const double orcaSoftMixStatus = ${softMix.status};`);
  w();
  w('/// Corner radii per shape, in logical pixels.');
  w('const Map<OrcaShape, OrcaRadii> orcaShapes = <OrcaShape, OrcaRadii>{');
  for (const [name, r] of Object.entries(shapes)) {
    w(`  OrcaShape.${shapeName(name)}: OrcaRadii(sm: ${r.sm}, md: ${r.md}, lg: ${r.lg}),`);
  }
  w('};');
  w();
  w('/// All resolved color themes: mode x accent.');
  w('const Map<OrcaMode, Map<OrcaAccent, OrcaColors>> orcaColorThemes =');
  w('    <OrcaMode, Map<OrcaAccent, OrcaColors>>{');
  for (const mode of modeNames) {
    w(`  OrcaMode.${mode}: <OrcaAccent, OrcaColors>{`);
    for (const accent of accentNames) {
      const t = resolveTheme(mode, accent);
      w(`    OrcaAccent.${accent}: OrcaColors(`);
      w(`      brightness: Brightness.${mode === 'dark' ? 'dark' : 'light'},`);
      for (const key of colorKeys) {
        if (!(key in t)) throw new Error(`resolveTheme(${mode}, ${accent}) is missing ${key}`);
        w(`      ${key}: ${dartColor(t[key])},`);
      }
      w('    ),');
    }
    w('  },');
  }
  w('};');
  w();
  return lines.join('\n');
}

/**
 * Independent check: parse the Dart file back and compare every color with the
 * web build output (packages/core/tokens.js, written by the core build script).
 */
async function crossCheck(dart) {
  const { themes } = await import('../../core/tokens.js');
  const parsed = {};
  let mode = null;
  let accent = null;
  for (const line of dart.split('\n')) {
    let m;
    if ((m = line.match(/^ {2}OrcaMode\.(\w+): /))) {
      mode = m[1];
    } else if ((m = line.match(/^ {4}OrcaAccent\.(\w+): OrcaColors\(/))) {
      accent = m[1];
      (parsed[mode] ??= {})[accent] = {};
    } else if ((m = line.match(/^ {6}(\w+): Color\(0x([0-9A-F]{8})\),/)) && mode && accent) {
      parsed[mode][accent][m[1]] = m[2];
    }
  }
  let checked = 0;
  for (const mode of modeNames) {
    for (const accent of accentNames) {
      for (const [key, web] of Object.entries(themes[mode][accent])) {
        const expected = dartColor(web).slice('Color(0x'.length, -1);
        const actual = parsed[mode]?.[accent]?.[key];
        if (actual !== expected) {
          throw new Error(`${mode}/${accent}/${key}: dart ${actual} != web ${web}`);
        }
        checked++;
      }
    }
  }
  return checked;
}

const content = generate();
if (process.argv.includes('--check')) {
  const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== content) {
    console.error('lib/src/tokens.g.dart is out of date. Run: node packages/flutter/tool/generate_tokens.mjs');
    process.exit(1);
  }
  const checked = await crossCheck(current);
  console.log(`lib/src/tokens.g.dart is up to date; ${checked} colors match packages/core/tokens.js.`);
} else {
  writeFileSync(out, content);
  console.log(`Wrote ${out} (${modeNames.length * accentNames.length} color themes, ${Object.keys(shapes).length} shapes).`);
}
