// Builds @pelagic-ui/illustrations: parses every scene source in src/scenes, validates it
// (token roles only, safe element subset) and writes dist/ — the runtime, typings,
// framework wrappers and standalone SVG files. Run: node scripts/build.mjs
import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src');
const dist = join(root, 'dist');

/** Display order (also the contact-sheet order). Each name maps to src/scenes/<name>.js. */
export const ORDER = [
  'no-data', 'no-results', 'filter-empty', 'empty-inbox', 'no-messages', 'no-comments',
  'no-notifications', 'empty-cart', 'no-payments', 'no-files', 'empty-folder', 'upload',
  'all-done', 'empty-calendar', 'no-team-members', 'no-favorites', 'welcome', 'coming-soon',
  'maintenance', 'offline', 'no-permission', 'error', 'not-found', 'server-error',
];

const TAGS = new Set(['g', 'path', 'circle', 'rect', 'ellipse', 'line', 'polyline', 'polygon']);
const ROLES = new Set(['accent', 'soft', 'paper', 'alt', 'muted', 'line', 'edge', 'ink', 'none']);
const ATTRS = new Set([
  'd', 'cx', 'cy', 'r', 'rx', 'ry', 'x', 'y', 'width', 'height', 'x1', 'y1', 'x2', 'y2', 'points', 'transform',
  'fill', 'stroke', 'stroke-width', 'stroke-linecap', 'stroke-linejoin', 'stroke-dasharray', 'stroke-opacity',
  'fill-opacity', 'opacity', 'fill-rule', 'float', 'detail', 'bg',
]);

/** Minimal parser for the controlled SVG subset used by scene sources. */
export function parse(markup, scene) {
  const rootNode = ['root', {}, []];
  const stack = [rootNode];
  const re = /<(\/?)([a-z]+)((?:\s+[a-z-]+="[^"]*")*)\s*(\/?)>/g;
  let last = 0;
  let m;
  while ((m = re.exec(markup))) {
    if (markup.slice(last, m.index).trim()) throw new Error(`${scene}: stray text "${markup.slice(last, m.index).trim()}"`);
    last = re.lastIndex;
    const [, closing, tag, rawAttrs, selfClosing] = m;
    if (!TAGS.has(tag)) throw new Error(`${scene}: <${tag}> is not allowed`);
    if (closing) {
      const open = stack.pop();
      if (!open || open[0] !== tag) throw new Error(`${scene}: mismatched </${tag}>`);
      continue;
    }
    const attrs = {};
    for (const [, k, v] of rawAttrs.matchAll(/([a-z-]+)="([^"]*)"/g)) {
      if (!ATTRS.has(k)) throw new Error(`${scene}: attribute "${k}" is not allowed`);
      if ((k === 'fill' || k === 'stroke') && !ROLES.has(v)) throw new Error(`${scene}: ${k}="${v}" must be a color role (${[...ROLES].join(', ')})`);
      attrs[k] = v;
    }
    if (attrs.float && attrs.transform) throw new Error(`${scene}: a float element cannot also carry transform (wrap it in <g>)`);
    const node = [tag, attrs, []];
    stack.at(-1)[2].push(node);
    if (!selfClosing) stack.push(node);
  }
  if (markup.slice(last).trim()) throw new Error(`${scene}: trailing text`);
  if (stack.length !== 1) throw new Error(`${scene}: unclosed <${stack.at(-1)[0]}>`);
  return rootNode[2];
}

// Compact JSON: drop empty children arrays.
const pack = (nodes) => nodes.map(([t, a, c]) => (c.length ? [t, a, pack(c)] : [t, a]));
const pascal = (name) => name.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('') + 'Illustration';

export async function loadScenes() {
  const scenes = {};
  const meta = [];
  for (const name of ORDER) {
    const mod = (await import(pathToFileURL(join(src, 'scenes', `${name}.js`)).href + `?t=${Date.now()}`)).default;
    scenes[name] = pack(parse(mod.body, name));
    meta.push({ name, title: mod.title, keywords: mod.keywords, component: pascal(name) });
  }
  return { scenes, meta };
}

async function build() {
  const { scenes, meta } = await loadScenes();
  rmSync(dist, { recursive: true, force: true });
  for (const dir of ['', 'svelte', 'astro', 'svg']) mkdirSync(join(dist, dir), { recursive: true });

  const header = '/* @pelagic-ui/illustrations — GENERATED by scripts/build.mjs from src/scenes. Do not edit. */\n';
  writeFileSync(join(dist, 'data.js'), `${header}export const SCENES = ${JSON.stringify(scenes)};\nexport const META = ${JSON.stringify(meta, null, 1)};\n`);
  copyFileSync(join(src, 'core.js'), join(dist, 'illustrations.js'));

  const union = ORDER.map((n) => `'${n}'`).join(' | ');
  const named = (decl) => meta.map((m) => decl(m)).join('\n');
  const fill = (file, replacements) => {
    let text = readFileSync(join(src, file), 'utf8');
    for (const [k, v] of Object.entries(replacements)) text = text.split(k).join(v);
    return header + text;
  };
  const reps = {
    '/*@NAMES_UNION*/': union,
    '/*@REACT_NAMED*/': named((m) => `export const ${m.component} = named('${m.name}', '${m.component}');`),
    '/*@REACT_NAMED_DTS*/': named((m) => `/** "${m.title}" scene. */\nexport declare const ${m.component}: NamedIllustration;`),
    '/*@VUE_NAMED*/': named((m) => `export const ${m.component} = named('${m.name}', '${m.component}');`),
    '/*@VUE_NAMED_DTS*/': named((m) => `/** "${m.title}" scene. */\nexport declare const ${m.component}: NamedIllustrationComponent;`),
    '/*@NATIVE_NAMED*/': named((m) => `export const ${m.component} = named('${m.name}');`),
    '/*@NATIVE_NAMED_DTS*/': named((m) => `/** "${m.title}" scene. */\nexport declare function ${m.component}(props: Omit<NativeIllustrationProps, 'name'>): ReactElement;`),
  };
  for (const [from, to] of [
    ['types.d.ts', 'illustrations.d.ts'],
    ['react.js', 'react.js'], ['react.d.ts', 'react.d.ts'],
    ['vue.js', 'vue.js'], ['vue.d.ts', 'vue.d.ts'],
    ['element.js', 'element.js'], ['element.d.ts', 'element.d.ts'],
    ['angular.js', 'angular.js'], ['angular.d.ts', 'angular.d.ts'],
    ['native.js', 'native.js'], ['native.d.ts', 'native.d.ts'],
    ['svelte/index.js', 'svelte/index.js'], ['svelte/index.d.ts', 'svelte/index.d.ts'],
  ]) writeFileSync(join(dist, to), fill(from, reps));
  // Component files keep their own syntax; no header comment inside .svelte/.astro frontmatter issues.
  copyFileSync(join(src, 'svelte/Illustration.svelte'), join(dist, 'svelte/Illustration.svelte'));
  copyFileSync(join(src, 'astro/Illustration.astro'), join(dist, 'astro/Illustration.astro'));
  writeFileSync(join(dist, 'data.d.ts'), `${header}export declare const SCENES: Record<string, unknown[]>;\nexport declare const META: { name: string; title: string; keywords: string[]; component: string }[];\n`);

  // Standalone SVG files (token variables with built-in fallbacks) for design tools and <img>.
  const { illustrationToSvg } = await import(pathToFileURL(join(dist, 'illustrations.js')).href + `?t=${Date.now()}`);
  for (const m of meta) writeFileSync(join(dist, 'svg', `${m.name}.svg`), illustrationToSvg(m.name, { animated: false }) + '\n');

  console.log(`Built @pelagic-ui/illustrations: ${meta.length} scenes → dist/ (runtime, d.ts, react, vue, svelte, astro, angular, element, native, svg).`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === join(process.argv[1])) await build();
